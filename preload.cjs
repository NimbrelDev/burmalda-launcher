const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getSettings: () => ipcRenderer.invoke('get-settings'),
  saveSettings: (settings) => ipcRenderer.invoke('save-settings', settings),
  getStatus: () => ipcRenderer.invoke('get-status'),
  getVersions: () => ipcRenderer.invoke('get-versions'),
  downloadVersion: (tag) => ipcRenderer.invoke('download-version', tag),
  setVersion: (tag, mcVersion) => ipcRenderer.invoke('set-version', tag, mcVersion),
  rollbackVersion: () => ipcRenderer.invoke('rollback-version'),
  selectSkin: () => ipcRenderer.invoke('select-skin'),
  resetSkin: () => ipcRenderer.invoke('reset-skin'),
  selectFile: (options) => ipcRenderer.invoke('select-file', options),
  getSkin: () => ipcRenderer.invoke('get-skin'),
  getDefaultSkins: () => ipcRenderer.invoke('get-default-skins'),
  selectDefaultSkin: (id) => ipcRenderer.invoke('select-default-skin', id),
  getWardrobe: () => ipcRenderer.invoke('get-wardrobe'),
  addToWardrobe: (name) => ipcRenderer.invoke('add-to-wardrobe', name),
  deleteFromWardrobe: (id) => ipcRenderer.invoke('delete-from-wardrobe', id),
  setActiveWardrobeSkin: (id) => ipcRenderer.invoke('set-active-wardrobe-skin', id),
  fetchSkinByName: (username) => ipcRenderer.invoke('fetch-skin-by-name', username),
  launchGame: (server) => ipcRenderer.invoke('launch-game', server),
  killGame: () => ipcRenderer.invoke('kill-game'),
  openFolder: (type) => ipcRenderer.invoke('open-folder', type),
  scanMods: () => ipcRenderer.invoke('scan-mods'),
  getSavedServers: () => ipcRenderer.invoke('get-saved-servers'),
  saveServers: (servers) => ipcRenderer.invoke('save-servers', servers),
  getTouchSettings: () => ipcRenderer.invoke('get-touch-settings'),
  saveTouchSettings: (settings) => ipcRenderer.invoke('save-touch-settings', settings),
  getFriends: () => ipcRenderer.invoke('get-friends'),
  saveFriends: (friends) => ipcRenderer.invoke('save-friends', friends),
  generateInviteCode: () => ipcRenderer.invoke('generate-invite-code'),
  onVersionProgress: (callback) => ipcRenderer.on('version-download-progress', (_, data) => callback(data)),
  onGameLog: (callback) => ipcRenderer.on('game-log', (_, text) => callback(text)),
  onGameExit: (callback) => ipcRenderer.on('game-exit', (_, code) => callback(code)),
  windowMin: () => ipcRenderer.send('window-min'),
  windowMax: () => ipcRenderer.send('window-max'),
  windowClose: () => ipcRenderer.send('window-close'),
});
